async function fixture({ reject = false, ambiguous = false, chainChange = false, pending = false, bulk = false, batchFailed = false, portraitFailure = false, tokens = [968, 1677], liveRecipientCheck = false } = {}) {
  let recoveryReady = !ambiguous
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  await context.addInitScript(({ from, to, hash, reject, ambiguous, chainChange, bulk, pending, batchFailed }) => {
    window.__walletCalls = []
    let chainReads = 0
    const provider = address => ({ request: async ({ method, params }) => {
      window.__walletCalls.push({ method, params, address })
      if (method === 'eth_requestAccounts' || method === 'eth_accounts') return [address]
      if (method === 'eth_chainId') { chainReads++; return chainChange && chainReads > 2 ? '0x1' : '0xab5' }
      if (method === 'wallet_switchEthereumChain') return null
      if (method === 'wallet_getCapabilities') return { '0xab5': { atomic: { status: bulk ? 'supported' : 'unsupported' } } }
      if (method === 'wallet_sendCalls') {
        if (reject) throw Object.assign(new Error('User rejected the request'), { code: 4001 })
        if (ambiguous) throw new Error('Wallet connection timed out')
        return { id: params[0].id }
      }
      if (method === 'wallet_getCallsStatus') return { id: params[0], chainId: '0xab5', atomic: true, status: batchFailed ? 400 : pending || ambiguous ? 100 : 200, receipts: pending || ambiguous || batchFailed ? [] : [{ transactionHash: hash }] }
      if (method === 'eth_sendTransaction') {
        if (reject) throw Object.assign(new Error('User rejected the request'), { code: 4001 })
        if (ambiguous) throw new Error('Wallet connection timed out')
        return hash
      }
      throw new Error(`Unexpected wallet request ${method}`)
    } })
    const sending = provider(from), receiving = provider(to)
    window.addEventListener('eip6963:requestProvider', () => {
      for (const [name, p] of [['Sending test wallet', sending], ['Receiving test wallet', receiving]]) window.dispatchEvent(new CustomEvent('eip6963:announceProvider', { detail: { info: { uuid: name, name, rdns: 'test.invalid' }, provider: p } }))
    })
  }, { from, to, hash, reject, ambiguous, chainChange, bulk, pending, batchFailed })
  const page = await context.newPage()
  if (portraitFailure) await page.route('**/deabstractor/glowbud-968.png', route => route.abort())
  page.on('pageerror', error => proof.errors.push(error.message))
  page.on('console', message => {
    if (message.type() === 'error' && !(portraitFailure && message.text().includes('Failed to load resource'))) proof.errors.push(message.text())
  })
  await page.route('**/api/deabstractor/inventory?*', route => route.fulfill({ json: { tokenIds: tokens, address: from, block: '123' } }))
  await page.route('**/api/deabstractor/check', route => {
    const data = route.request().postDataJSON()
    // Optional integration proof uses real read-only wallet classification only.
    if (liveRecipientCheck) return data.action === 'recipient' ? route.continue() : route.abort()
    if (data.action === 'recipient') return route.fulfill({ json: { address: data.to, checkedAt: Date.now() } })
    if (data.action === 'preflight') return route.fulfill({ json: { ready: true } })
    if (data.action === 'preflight-departure') return route.fulfill({ json: { ready: true, fromBlock: '123' } })
    if (data.action === 'departure') return route.fulfill({ json: { complete: !pending && recoveryReady, records: !data.hash && !recoveryReady ? [] : data.tokens.map(token => ({ from: data.from, to: data.to, token, hash: data.hash || hash, status: pending ? 'pending' : 'confirmed', atDestination: !pending })) } })
    return route.fulfill({ json: { status: pending ? 'pending' : 'confirmed', atDestination: !pending, currentOwner: to, block: '456' } })
  })
  await page.goto(`${base}/deabstractor`, { waitUntil: 'domcontentloaded' })
  if (portraitFailure) await page.getByRole('button', { name: 'Open wallet desk', exact: true }).click({ timeout: 30000 })
  await page.getByRole('button', { name: 'Use a browser wallet', exact: true }).waitFor({ timeout: 60000 })
  return { page, context, resolve: () => { recoveryReady = true } }
}
async function shot(page, name) {
  await page.evaluate(() => document.fonts.ready)
  await page.waitForTimeout(250)
  const buffer = await page.screenshot({ path: path.join(out, `${name}.png`) })
  const image = PNG.sync.read(buffer), colors = new Set()
  for (let i = 0; i < image.data.length; i += 80) colors.add(`${image.data[i] >> 4}:${image.data[i + 1] >> 4}:${image.data[i + 2] >> 4}`)
  assert(colors.size > 65, `${name}: blank scene`)
  assert(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), `${name}: horizontal overflow`)
  proof.screenshots.push({ name, colors: colors.size })
}
